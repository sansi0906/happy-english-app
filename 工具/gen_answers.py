def build():
    doc = Document()
    L.setup_page(doc, draw_line=False)
    L.add_footer_page(doc, 4)
    L.para(doc, '一年级上册期末复习卷 · 参考答案', size=20, name='黑体', bold=True,
           before=0, after=4, line=30, align='center')
    L.para(doc, '（人教版 2024 · 天津）', size=11, name='宋体', after=8, line=18, align='center')
    for i, (title, blocks) in enumerate(PAGES):
        p = L.para(doc, title, size=15, name='黑体', bold=True, before=4, after=4, line=24)
        if i > 0:
            p.paragraph_format.page_break_before = True
        for sec, lines in blocks:
            L.para(doc, sec, size=13, name='黑体', bold=True, before=6, after=2, line=20)
            for ln in lines:
                L.para(doc, ln, size=13, name='楷体', after=0, line=20, indent_left=16)
    # 卷尾说明
    L.para(doc, '说明：写话、组词、照样子写句子等开放性题目，答案不唯一，意思正确、语句通顺即可给分。',
           size=11, name='宋体', before=10, line=20, indent_left=16)
    path = os.path.join(OUT, '期末卷_参考答案.docx')
    doc.save(path)
    print('saved', path)


if __name__ == '__main__':
    build()
