def no_border_table(doc, rows, cols, widths):
    tbl = doc.add_table(rows=rows, cols=cols)
    tbl.autofit = False
    tblPr = tbl._tbl.tblPr
    bd = parse_xml('<w:tblBorders %s>'
                   '<w:top w:val="none" w:sz="0" w:space="0" w:color="auto"/>'
                   '<w:left w:val="none" w:sz="0" w:space="0" w:color="auto"/>'
                   '<w:bottom w:val="none" w:sz="0" w:space="0" w:color="auto"/>'
                   '<w:right w:val="none" w:sz="0" w:space="0" w:color="auto"/>'
                   '<w:insideH w:val="none" w:sz="0" w:space="0" w:color="auto"/>'
                   '<w:insideV w:val="none" w:sz="0" w:space="0" w:color="auto"/>'
                   '</w:tblBorders>' % L.nsdecls('w'))
    tblPr.append(bd)
    for row in tbl.rows:
        for i, cell in enumerate(row.cells):
            cell.width = widths[i]
    return tbl


def fill_cell(cell, text, size=16, align='left'):
    p = cell.paragraphs[0]
    p.alignment = {'left': WD_ALIGN_PARAGRAPH.LEFT, 'center': WD_ALIGN_PARAGRAPH.CENTER,
                   'right': WD_ALIGN_PARAGRAPH.RIGHT}[align]
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = Pt(30)
    r = p.add_run(text)
    L.style_font(r, size, '楷体')


def connect_table(doc, rows, h=Cm(0.9)):
    tbl = no_border_table(doc, len(rows), 3, [Cm(3.0), Cm(2.0), Cm(3.0)])
    tbl.alignment = 1  # 居中
    for i, (a, b) in enumerate(rows):
        tr = tbl.rows[i]
        tr.height = h
        trPr = tr._tr.get_or_add_trPr()
        trPr.append(parse_xml('<w:cantSplit %s/>' % L.nsdecls('w')))
        fill_cell(tr.cells[0], a, align='center')
        fill_cell(tr.cells[1], '', align='center')
        fill_cell(tr.cells[2], b, align='center')
    return tbl


def is_num_item(text):
    s = text.strip()
    return len(s) > 2 and s[0].isdigit() and s[1] == '.'


def is_new_item(text):
    s = text.strip()
    if is_num_item(text):
        return True
    if s[:1] in ('①', '②', '③', '④', '⑤', '⑥'):
        return True
    return False


def blank(doc, n=1):
    for _ in range(n):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.space_before = Pt(0)
        pf.space_after = Pt(0)
        pf.line_spacing = Pt(BODY['line'])
        pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY


def build(title, sub, parts, note, body=None):
    body = body or BODY
    doc = Document()
    L.setup_page(doc)
    L.add_footer_page(doc, 4)
    L.exam_head(doc, title, sub, len(parts), note=note)
    if '语文' in title:
        pb = ('五、阅读',)
    elif '数学' in title and '基础' in title:
        pb = ('五、认一认',)   # 连线表整块同页，避免表格被拆到两页
    else:
        pb = ()
    for name, items in parts:
        head_p = L.h1(doc, name)
        # 整块另起一页：避免方格/连线表被拆页、末页收尾更整齐
        if name.startswith(pb):
            head_p.paragraph_format.page_break_before = True
        texts = [it[1] for it in items if it[0] in ('q', 'math')]
        attach = 0   # 当前题干后已跟随的行数，限制 keep 链长度，避免整页留白
        for idx, it in enumerate(items):
            k = it[0]
            if k == 'q':
                ind = it[2] if len(it) > 2 else body['indent']
                p = L.q(doc, it[1], size=body['size'], line=body['line'],
                        after=body['after'], indent=ind)
                # 小题题干绑定首行；作答行最多再跟随 2 行；圈号小问不串联整组
                if idx < len(items) - 1 and items[idx + 1][0] in ('q', 'math', 'pair', 'mz', 'tip'):
                    if is_num_item(it[1]):
                        p.paragraph_format.keep_with_next = True
                        attach = 0
                    elif not is_new_item(it[1]) and attach < 2:
                        p.paragraph_format.keep_with_next = True
                        attach += 1
                    else:
                        attach = 0
                else:
                    attach = 0
            elif k == 'math':
                for j, row in enumerate(it[1]):
                    p = L.q(doc, row, size=body['size'], line=body['line'],
                            after=body['after'], indent=32)
                    if j < len(it[1]) - 1:
                        p.paragraph_format.keep_with_next = True
            elif k == 'pair':
                if doc.paragraphs:
                    doc.paragraphs[-1].paragraph_format.keep_with_next = True
                connect_table(doc, it[1])
            elif k == 'mz':
                if doc.paragraphs:
                    doc.paragraphs[-1].paragraph_format.keep_with_next = True
                ind = it[2] if len(it) > 2 else 32
                L.mizige_row(doc, it[1], indent=ind, after=4)
            elif k == 'c':
                p = L.para(doc, it[1], size=body['size'], align='center',
                           line=body['line'], after=0)
                p.paragraph_format.keep_with_next = True
            elif k == 'grid':
                if doc.paragraphs:
                    doc.paragraphs[-1].paragraph_format.keep_with_next = True
                L.write_grid(doc, rows=it[1], cols=it[2], cell_cm=0.95)
            elif k == 'tip':
                p = L.para(doc, it[1], size=13, name='宋体', indent_left=32, line=22)
                p.paragraph_format.keep_with_next = True
            elif k == 'blank':
                blank(doc, it[1])
    # 卷尾：检查提示 + 签字栏
    blank(doc, 3)
    L.para(doc, '检查完了吗？再看看有没有漏题，字写得工整吗？', size=11,
           name='宋体', indent_left=16, line=20)
    L.para(doc, '家长签字：____________　　教师评语：____________', size=11,
           name='宋体', indent_left=16, line=24)
    return doc


